PERF_ROOT = (ROOT_DIR / ".womap-data" / "perf").resolve()


def require_report_path(path: Path) -> Path:
    resolved = path.resolve()
    if resolved == PERF_ROOT or PERF_ROOT not in resolved.parents:
        raise ValueError("PostGIS workstation reports must stay below .womap-data/perf")
    return resolved


async def run_workstation_postgis(feature_count: int) -> dict[str, object]:
    settings = get_settings()
    if not settings.database.uses_postgis:
        raise RuntimeError("workstation PostGIS benchmark requires PostgreSQL")
    schema = f"womap_perf_{uuid4().hex[:16]}"
    engine = create_async_engine(
        settings.database.sqlalchemy_url(),
        connect_args=settings.database.connect_args(),
        pool_pre_ping=True,
    )
    workloads: list[Workload] = ["bbox", "point", "line", "polygon"]
    bbox = (24_000.0, 24_000.0, 26_000.0, 26_000.0)
    try:
        async with engine.connect() as connection:
            await connection.execute(text(f'CREATE SCHEMA "{schema}"'))
            await connection.execute(text(f'SET search_path TO "{schema}", public'))
            await connection.execute(
                text(
                    """
                    CREATE TABLE map_features (
                      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      layer_id integer NOT NULL,
                      source_feature_id varchar(255),
                      properties jsonb NOT NULL DEFAULT '{}'::jsonb,
                      revision integer NOT NULL DEFAULT 1,
                      geom geometry(Polygon, 3857) NOT NULL
                    )
                    """
                )
            )
            await connection.execute(
                text(
                    """
                    INSERT INTO map_features (
                      layer_id, source_feature_id, properties, revision, geom
                    )
                    SELECT
                      1,
                      'perf-' || value,
                      jsonb_build_object('group', value % 17),
                      1,
                      ST_MakeEnvelope(
                        ((value - 1) % 1000) * 100.0,
                        floor((value - 1) / 1000.0) * 100.0,
                        ((value - 1) % 1000) * 100.0 + 80.0,
                        floor((value - 1) / 1000.0) * 100.0 + 80.0,
                        3857
                      )
                    FROM generate_series(1, :feature_count) AS value
                    """
                ),
                {"feature_count": feature_count},
            )
            await connection.execute(
                text("CREATE INDEX ix_perf_layer_id ON map_features (layer_id)")
            )
            await connection.execute(
                text("CREATE INDEX ix_perf_geom_gist ON map_features USING gist (geom)")
            )
            await connection.execute(
                text("CREATE INDEX ix_perf_layer_cursor ON map_features (layer_id, id)")
            )
            await connection.commit()

            before = await capture_plans_on_connection(
                connection,
                workloads=workloads,
                layer_id=1,
                bbox=bbox,
                limit=2000,
                distance_meters=250,
            )
            needs_analyze = any(
                item["summary"]["statistics_misaligned_over_10x"]
                for item in before.values()
            )
            after = None
            if needs_analyze:
                await connection.execute(text("ANALYZE map_features"))
                after = await capture_plans_on_connection(
                    connection,
                    workloads=workloads,
                    layer_id=1,
                    bbox=bbox,
                    limit=2000,
                    distance_meters=250,
                )
            return {
                "feature_count": feature_count,
                "before_analyze": before,
                "analyze_applied": needs_analyze,
                "after_analyze": after,
                "statistics_repaired": (
                    all(
                        not item["summary"]["statistics_misaligned_over_10x"]
                        for item in after.values()
                    )
                    if after is not None
                    else None
                ),
            }
    finally:
        try:
            async with engine.begin() as cleanup:
                await cleanup.execute(text(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE'))
        finally:
            await engine.dispose()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run four production PostGIS plans in an isolated temporary schema."
    )
    parser.add_argument("--feature-count", type=int, default=1_000_000)
    parser.add_argument("--confirm-large", action="store_true")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(".womap-data/perf/reports/postgis-workstation-medium.json"),
    )
    arguments = parser.parse_args()
    if arguments.feature_count > 100_000 and not arguments.confirm_large:
        parser.error("feature counts above 100000 require --confirm-large")
    if not 1 <= arguments.feature_count <= 1_000_000:
        parser.error("feature-count must be between 1 and 1000000")
    result = asyncio.run(run_workstation_postgis(arguments.feature_count))
    write_report(
        require_report_path(arguments.output),
        build_report(
            kind="postgis-workstation",
            profile="workstation-medium",
            dataset_tier="workstation-medium",
            workload={
                "queries": ["bbox", "point", "line", "polygon"],
                "feature_count": arguments.feature_count,
                "temporary_schema": True,
                "cleanup": "exact-run-id",
            },
            metrics=result,
        ),
    )
    print("PostGIS workstation plans captured; temporary schema was dropped.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
